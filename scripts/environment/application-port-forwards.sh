#!/usr/bin/env bash

set -euo pipefail

NAMESPACE="${KUBE_NAMESPACE:-hmcts-local}"
WAIT_SECONDS="${APPLICATION_WAIT_SECONDS:-600}"
STATE_DIR="${TMPDIR:-/tmp}/wa-kube-environment-$(id -u)"
ENV_FILE="${SERVICE_PORTS_ENV_FILE:-.service-ports.env}"

# service|local port|service port
FORWARDS=(
  "wiremock|18081|80"
  "ccd-definition-store-api|18082|80"
  "sidam-simulator|5556|80"
  "service-auth-provider-api|18084|80"
  "ccd-api-gateway|18085|80"
  "am-role-assignment|18086|80"
  "camunda-local-bpm|18087|80"
  "ccd-data-store-api|18088|80"
)

usage() {
  echo "Usage: $(basename "$0") <start|stop|status>"
}

pid_file() {
  echo "${STATE_DIR}/application-$1.pid"
}

log_file() {
  echo "${STATE_DIR}/application-$1.log"
}

is_running() {
  local service="$1"
  local expected_mapping="${2:-}"
  local file
  local pid
  local command

  file="$(pid_file "$service")"
  [[ -f "$file" ]] || return 1

  pid="$(cat "$file")"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  kill -0 "$pid" 2>/dev/null || return 1

  command="$(ps -p "$pid" -o command= 2>/dev/null || true)"
  [[ "$command" == *"kubectl"* &&
    "$command" == *"port-forward"* &&
    "$command" == *"service/${service}"* ]] || return 1

  [[ -z "$expected_mapping" || "$command" == *"$expected_mapping"* ]]
}

wait_for_endpoint() {
  local service="$1"
  local elapsed=0
  local addresses

  echo "Waiting for ${NAMESPACE}/${service} to have a ready endpoint..."
  until addresses="$(kubectl -n "$NAMESPACE" get endpoints "$service" \
    -o jsonpath='{.subsets[*].addresses[*].ip}' 2>/dev/null)" && [[ -n "$addresses" ]]; do
    if (( elapsed >= WAIT_SECONDS )); then
      echo "Timed out after ${WAIT_SECONDS}s waiting for ${NAMESPACE}/${service}." >&2
      return 1
    fi
    sleep 5
    elapsed=$((elapsed + 5))
  done
}

start_forward() {
  local service="$1"
  local local_port="$2"
  local remote_port="$3"
  local pid_path
  local output_path
  local pid
  local attempt

  pid_path="$(pid_file "$service")"
  output_path="$(log_file "$service")"

  if is_running "$service" "${local_port}:${remote_port}"; then
    echo "${service} is already forwarded by PID $(cat "$pid_path")."
    return
  fi

  if is_running "$service"; then
    echo "${service} forwarding configuration changed; restarting it."
    stop_forward "$service"
  fi

  rm -f "$pid_path" "$output_path"
  nohup kubectl -n "$NAMESPACE" port-forward \
    --address 127.0.0.1 \
    "service/${service}" \
    "${local_port}:${remote_port}" >"$output_path" 2>&1 &
  pid=$!
  printf '%s\n' "$pid" >"$pid_path"

  for attempt in {1..30}; do
    if ! kill -0 "$pid" 2>/dev/null; then
      echo "Could not forward ${service} to localhost:${local_port}:" >&2
      cat "$output_path" >&2
      rm -f "$pid_path"
      return 1
    fi

    if grep -q "Forwarding from 127.0.0.1:${local_port}" "$output_path"; then
      echo "${service}: localhost:${local_port} -> ${service}:${remote_port} (PID ${pid})"
      return
    fi
    sleep 1
  done

  echo "Timed out starting the port-forward for ${service}." >&2
  cat "$output_path" >&2
  return 1
}

stop_forward() {
  local service="$1"
  local pid_path
  local pid

  pid_path="$(pid_file "$service")"
  if ! is_running "$service"; then
    rm -f "$pid_path"
    echo "${service} is not currently forwarded."
    return
  fi

  pid="$(cat "$pid_path")"
  kill "$pid"
  rm -f "$pid_path"
  echo "Stopped the port-forward for ${service} (PID ${pid})."
}

write_env_file() {
  {
    echo "# Generated by scripts/environment/application-port-forwards.sh"
    echo "export WIREMOCK_URL=http://127.0.0.1:18081"
    echo "export CCD_SEARCH_URL=http://127.0.0.1:18081"
    echo "export CCD_DEFINITION_STORE=http://127.0.0.1:18082"
    echo "export CCD_DEFINITION_URL=http://127.0.0.1:18082"
    echo "export IDAM_URL=http://localhost:5556"
    echo "export IDAM_API_URL=http://localhost:5556"
    echo "export IDAM_API_BASE_URI=http://localhost:5556"
    echo "export IDAM_STUB_LOCALHOST=http://localhost:5556"
    echo "export OPEN_ID_IDAM_URL=http://localhost:5556"
    echo "export S2S_URL=http://127.0.0.1:18084"
    echo "export CCD_GW_URL=http://127.0.0.1:18085"
    echo "export ROLE_ASSIGNMENT_URL=http://127.0.0.1:18086"
    echo "export CAMUNDA_URL=http://127.0.0.1:18087/engine-rest"
    echo "export CCD_URL=http://127.0.0.1:18088"
  } >"$ENV_FILE"

  echo "Local service settings written to ${ENV_FILE}."
}

mkdir -p "$STATE_DIR"

case "${1:-}" in
  start)
    if ! kubectl cluster-info >/dev/null 2>&1; then
      echo "Kubernetes is not reachable. Start the environment first:" >&2
      echo "  make environment-up-no-admin" >&2
      exit 1
    fi
    for entry in "${FORWARDS[@]}"; do
      IFS='|' read -r service local_port remote_port <<<"$entry"
      wait_for_endpoint "$service"
      start_forward "$service" "$local_port" "$remote_port"
    done
    write_env_file
    ;;
  stop)
    for entry in "${FORWARDS[@]}"; do
      IFS='|' read -r service _ _ <<<"$entry"
      stop_forward "$service"
    done
    ;;
  status)
    for entry in "${FORWARDS[@]}"; do
      IFS='|' read -r service local_port remote_port <<<"$entry"
      if is_running "$service" "${local_port}:${remote_port}"; then
        echo "${service}: running on localhost:${local_port} (PID $(cat "$(pid_file "$service")"))"
      else
        echo "${service}: stopped"
      fi
    done
    ;;
  *)
    usage
    exit 1
    ;;
esac

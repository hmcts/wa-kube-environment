#!/usr/bin/env bash

set -euo pipefail

NAMESPACE="${KUBE_NAMESPACE:-hmcts-local}"
PRIMARY_SERVICE="ccd-shared-database"
REPLICA_SERVICE="ccd-shared-database-replica"
PRIMARY_LOCAL_PORT="${POSTGRES_LOCAL_PORT:-15432}"
REPLICA_LOCAL_PORT="${POSTGRES_REPLICA_LOCAL_PORT:-15433}"
REMOTE_PORT=5432
WAIT_SECONDS="${DATABASE_WAIT_SECONDS:-600}"
STATE_DIR="${TMPDIR:-/tmp}/wa-kube-environment-$(id -u)"
ENV_FILE="${DB_PORTS_ENV_FILE:-.db-ports.env}"

usage() {
  echo "Usage: $(basename "$0") <start|stop|status>"
}

pid_file() {
  echo "${STATE_DIR}/$1.pid"
}

log_file() {
  echo "${STATE_DIR}/$1.log"
}

is_running() {
  local service="$1"
  local expected_mapping="${2:-}"
  local file
  local pid
  local command

  file="$(pid_file "$service")"
  [[ -f "$file" ]] || return 1

  pid="$(cat "$file")"
  [[ "$pid" =~ ^[0-9]+$ ]] || return 1
  kill -0 "$pid" 2>/dev/null || return 1

  command="$(ps -p "$pid" -o command= 2>/dev/null || true)"
  [[ "$command" == *"kubectl"* &&
    "$command" == *"port-forward"* &&
    "$command" == *"service/${service}"* ]] || return 1

  [[ -z "$expected_mapping" || "$command" == *"$expected_mapping"* ]]
}

wait_for_endpoint() {
  local service="$1"
  local elapsed=0
  local addresses

  echo "Waiting for ${NAMESPACE}/${service} to have a ready endpoint..."
  until addresses="$(kubectl -n "$NAMESPACE" get endpoints "$service" \
    -o jsonpath='{.subsets[*].addresses[*].ip}' 2>/dev/null)" && [[ -n "$addresses" ]]; do
    if (( elapsed >= WAIT_SECONDS )); then
      echo "Timed out after ${WAIT_SECONDS}s waiting for ${NAMESPACE}/${service}." >&2
      return 1
    fi
    sleep 5
    elapsed=$((elapsed + 5))
  done
}

start_forward() {
  local service="$1"
  local local_port="$2"
  local pid_path
  local output_path
  local pid
  local attempt

  pid_path="$(pid_file "$service")"
  output_path="$(log_file "$service")"

  if is_running "$service" "${local_port}:${REMOTE_PORT}"; then
    echo "${service} is already forwarded by PID $(cat "$pid_path")."
    return
  fi

  if is_running "$service"; then
    echo "${service} forwarding configuration changed; restarting it."
    stop_forward "$service"
  fi

  rm -f "$pid_path" "$output_path"
  nohup kubectl -n "$NAMESPACE" port-forward \
    --address 127.0.0.1 \
    "service/${service}" \
    "${local_port}:${REMOTE_PORT}" >"$output_path" 2>&1 &
  pid=$!
  printf '%s\n' "$pid" >"$pid_path"

  for attempt in {1..30}; do
    if ! kill -0 "$pid" 2>/dev/null; then
      echo "Could not forward ${service} to localhost:${local_port}:" >&2
      cat "$output_path" >&2
      rm -f "$pid_path"
      return 1
    fi

    if grep -q "Forwarding from 127.0.0.1:${local_port}" "$output_path"; then
      echo "${service}: localhost:${local_port} -> ${service}:${REMOTE_PORT} (PID ${pid})"
      return
    fi
    sleep 1
  done

  echo "Timed out starting the port-forward for ${service}." >&2
  cat "$output_path" >&2
  return 1
}

stop_forward() {
  local service="$1"
  local pid_path
  local pid

  pid_path="$(pid_file "$service")"
  if ! is_running "$service"; then
    rm -f "$pid_path"
    echo "${service} is not currently forwarded."
    return
  fi

  pid="$(cat "$pid_path")"
  kill "$pid"
  rm -f "$pid_path"
  echo "Stopped the port-forward for ${service} (PID ${pid})."
}

write_env_file() {
  {
    echo "# Generated by scripts/environment/database-port-forwards.sh"
    echo "export POSTGRES_HOST=127.0.0.1"
    echo "export POSTGRES_CLUSTER_HOST=ccd-shared-database"
    echo "export POSTGRES_REPLICA_HOST=127.0.0.1"
    echo "export POSTGRES_PORT=${PRIMARY_LOCAL_PORT}"
    echo "export POSTGRES_REPLICA_PORT=${REPLICA_LOCAL_PORT}"
    echo "export REPLICATION_SUBSCRIPTIONURL=postgresql://ccd-shared-database:5432"
  } >"$ENV_FILE"

  echo "Local database settings written to ${ENV_FILE}."
  echo "Run: source scripts/environment/activate-local-databases.sh"
}

mkdir -p "$STATE_DIR"

case "${1:-}" in
  start)
    if ! kubectl cluster-info >/dev/null 2>&1; then
      echo "Kubernetes is not reachable. Start the environment first:" >&2
      echo "  make environment-up-no-admin" >&2
      exit 1
    fi
    wait_for_endpoint "$PRIMARY_SERVICE"
    wait_for_endpoint "$REPLICA_SERVICE"
    start_forward "$PRIMARY_SERVICE" "$PRIMARY_LOCAL_PORT"
    start_forward "$REPLICA_SERVICE" "$REPLICA_LOCAL_PORT"
    write_env_file
    ;;
  stop)
    stop_forward "$PRIMARY_SERVICE"
    stop_forward "$REPLICA_SERVICE"
    ;;
  status)
    for service_and_port in \
      "${PRIMARY_SERVICE}|${PRIMARY_LOCAL_PORT}" \
      "${REPLICA_SERVICE}|${REPLICA_LOCAL_PORT}"; do
      IFS='|' read -r service local_port <<<"$service_and_port"
      if is_running "$service" "${local_port}:${REMOTE_PORT}"; then
        echo "${service}: running (PID $(cat "$(pid_file "$service")"))"
      else
        echo "${service}: stopped"
      fi
    done
    ;;
  *)
    usage
    exit 1
    ;;
esac
